function SelectItem({
  className,
  children,
  ...props
}: SelectPrimitive.Item.Props) {
  return (
    <SelectPrimitive.Item
      data-slot="select-item"
      className={cn(
        // The same row a menu is made of (`console/menu`'s `menuRowClass`), so a
        // select's options and a menu's items cannot drift apart.
        "relative flex h-8 w-full cursor-default items-center gap-2.25 rounded-md py-1 pr-8 pl-2.25 text-body outline-hidden select-none focus:bg-raise data-disabled:pointer-events-none data-disabled:opacity-50 data-selected:font-medium data-selected:text-brand-tx [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 *:[span]:last:flex *:[span]:last:items-center *:[span]:last:gap-2",
        className
      )}
      {...props}
    >
      {/* **`min-w-0`, not `shrink-0` (F14).** The popup is `w-(--anchor-width)`
          with `overflow-x-hidden`, and `Picker` documents its label as
          truncating — which it was not: `shrink-0` here means this box never
          drops below its content width, so a child's `truncate` has nothing to
          truncate against and the text overflows and is *clipped* by the popup
          instead. `min-w-0` on the child cannot fix a parent that refuses to
          shrink. Found by driving a picker of Docker container names, where
          `mariadb-1lz139.1.vh5l2ai…` stopped mid-string with no ellipsis and two
          different containers rendered as the same visible text. */}
      <SelectPrimitive.ItemText className="flex min-w-0 flex-1 gap-2 whitespace-nowrap">
        {children}
      </SelectPrimitive.ItemText>
      <SelectPrimitive.ItemIndicator
        render={
          <span className="pointer-events-none absolute right-2 flex size-4 items-center justify-center" />
        }
      >
        <CheckIcon className="pointer-events-none" />
      </SelectPrimitive.ItemIndicator>
    </SelectPrimitive.Item>
  )
}

