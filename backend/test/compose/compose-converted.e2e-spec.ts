// The same stack as `WORDPRESS_COMPOSE` **after a first deploy has converted
// it** — one https domain on `wordpress`, routed on the shared network, with
// both platform defaults already written. This is what
// `getComposeFilePath(compose)` holds for a git-sourced stack once
// `getBuildComposeCommand` has overwritten the clone with its own output, and
// therefore what `ComposeService.readComposeFile` hands `getConverted` on every
// read after the first deploy.
//
// Hand-written on purpose, and read as the *input* half of the assertion below
// (§1.7): it is not generated by `createComposeDomainLabels` and must not be, or
// the case would agree with a broken builder instead of stating what a converted
// file looks like. Twelve labels — `traefik.enable`, the routed-network label,
// and the five-label web/websecure pair an https domain earns.
